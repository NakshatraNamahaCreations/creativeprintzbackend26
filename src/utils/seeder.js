const seed = async () => {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('✅ MongoDB Connected');

    await Category.deleteMany({});
    await Product.deleteMany({});
    console.log('🗑️  Cleared existing data');

    const createdCats = await Category.insertMany(categories);
    const catMap = {};
    createdCats.forEach((c) => { catMap[c.slug] = c._id; });
    console.log(`✅ Created ${createdCats.length} categories`);

    const products = getProducts(catMap).map((p) => ({
      ...p,
      images: p.images?.length ? p.images : makeImages(p.slug),
    }));
    await Product.insertMany(products);
    console.log(`✅ Created ${products.length} products`);

    const adminExists = await User.findOne({ email: 'admin@creativeprintz.in' });
    if (!adminExists) {
      await User.create({
        name: 'Admin',
        email: 'admin@creativeprintz.in',
        password: 'admin@123',
        role: 'admin',
        isEmailVerified: true,
      });
      console.log('✅ Admin user: admin@creativeprintz.in / admin@123');
    }

    console.log('\n🎉 Database seeded successfully!');
    console.log('─────────────────────────────────────────────');
    console.log(`📦 ${products.length} products across ${createdCats.length} categories`);
    console.log('👤 Admin: admin@creativeprintz.in / admin@123');
    console.log('─────────────────────────────────────────────');
    process.exit(0);
  } catch (error) {
    console.error('❌ Seeding failed:', error.message);
    process.exit(1);
  }
};

seed();
